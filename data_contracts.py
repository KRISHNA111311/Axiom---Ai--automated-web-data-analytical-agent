from dataclasses import dataclass, field
from typing import Optional, List, Dict, Any, Literal
from datetime import datetime

# ------------------------------
# Step 25: RawPageBundle
# ------------------------------
@dataclass
class RawPageBundle:
    url: str
    html: str
    fetched_at: str  # ISO datetime string
    source: Literal["direct", "brightdata"]
    status_code: int

# ------------------------------
# Step 26: SanitizedRecord
# ------------------------------
@dataclass
class SanitizedRecord:
    title: str
    category: str
    price: float
    currency: str = "GBP"
    rating: Optional[int] = None
    availability: Optional[str] = None
    source_url: str = ""

# ------------------------------
# Step 27: SchemaProfile
# ------------------------------
@dataclass
class SchemaProfile:
    table_name: str
    columns: List[Dict[str, Any]]  # list of {name, dtype, null_ratio}
    row_count: int

# ------------------------------
# Step 28: CorrelationResult
# ------------------------------
@dataclass
class CorrelationResult:
    matrix: Dict[str, Dict[str, float]]
    columns: List[str]

# ------------------------------
# Step 29: BinnedStatsResult
# ------------------------------
@dataclass
class BinnedStatsResult:
    column: str
    bin_edges: List[float]
    counts: List[int]

# ------------------------------
# Step 30: GroupStatsResult
# ------------------------------
@dataclass
class GroupStatsResult:
    group_column: str
    value_column: str
    groups: List[Dict[str, Any]]  # each dict: {group_name, n, mean, median, std, skewness, kurtosis}

# ------------------------------
# Step 31: ClassBalanceResult
# ------------------------------
@dataclass
class ClassBalanceResult:
    label_column: str
    class_counts: Dict[str, int]
    imbalance_ratio: float  # majority / minority

# ------------------------------
# Step 32: TimeSeriesStatsResult
# ------------------------------
@dataclass
class TimeSeriesStatsResult:
    time_column: str
    value_column: str
    rolling_mean_by_bucket: List[float]
    rolling_var_by_bucket: List[float]
    lag1_autocorr: float

# ------------------------------
# Step 33: ProfileBundle (Container)
# ------------------------------
@dataclass
class ProfileBundle:
    schema_profile: Optional[SchemaProfile] = None
    missing_values: Optional[Dict[str, float]] = None
    correlations: Optional[CorrelationResult] = None
    binned_stats: Optional[BinnedStatsResult] = None
    group_stats: Optional[GroupStatsResult] = None
    class_balance: Optional[ClassBalanceResult] = None
    time_series_stats: Optional[TimeSeriesStatsResult] = None

# ------------------------------
# Step 34: AuditVerdict
# ------------------------------
@dataclass
class AuditVerdict:
    task_type: Literal["group_comparison", "regression", "classification", "timeseries"]
    passed: bool
    findings: List[str] = field(default_factory=list)
    recommended_test_or_model: str = ""
    excluded_groups: Optional[List[str]] = None

# ------------------------------
